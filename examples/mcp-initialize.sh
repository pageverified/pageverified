#!/bin/sh
# Open an MCP session with PageVerified. No API key is needed and no tool runs.
curl -s -X POST https://pageverified.com/mcp \
  -H "content-type: application/json" \
  -H "accept: application/json, text/event-stream" \
  -d '{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18","capabilities":{},"clientInfo":{"name":"example","version":"1.0.0"}}}'
echo
